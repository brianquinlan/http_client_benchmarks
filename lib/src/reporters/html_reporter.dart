// Hides unchecked clients and recomputes relative values against the clients
// that remain visible. Mirrors `Metric.ratio` and `scoreVariants`.
const _script = r'''
const hidden = new Set();

function ratio(value, best, higher, floor) {
  if (value === best) return 1;
  if (higher) return best === 0 ? 0 : value / best;
  const denominator = Math.max(value, floor);
  return denominator === 0 ? 1 : Math.max(best, floor) / denominator;
}

function visible(elements) {
  return [...elements].filter((e) => !hidden.has(e.dataset.variant));
}

function best(values, higher) {
  return values.reduce((a, b) => (higher ? Math.max(a, b) : Math.min(a, b)));
}

function update() {
  for (const bars of document.querySelectorAll('.bars[data-higher]')) {
    const higher = bars.dataset.higher === 'true';
    const floor = Number(bars.dataset.floor);
    const tracks = visible(bars.querySelectorAll('.track[data-value]'));
    if (tracks.length === 0) continue;
    const top = best(tracks.map((t) => Number(t.dataset.value)), higher);
    for (const track of tracks) {
      const r = ratio(Number(track.dataset.value), top, higher, floor);
      track.firstElementChild.style.width = `${(r * 100).toFixed(1)}%`;
    }
  }

  const ratios = {};
  const wins = {};
  let scored = 0;
  let speed = 0;
  for (const row of document.querySelectorAll('tr[data-higher]')) {
    const higher = row.dataset.higher === 'true';
    const floor = Number(row.dataset.floor);
    const memory = row.dataset.memory === 'true';
    const all = visible(row.querySelectorAll('td[data-variant]'));
    const cells = all.filter((c) => c.dataset.value !== undefined);
    if (!memory) speed++;
    if (cells.length === 0) continue;
    const top = best(cells.map((c) => Number(c.dataset.value)), higher);
    // Like `scoreVariants`, only score scenarios that every visible client
    // completed using its expected protocol.
    const scoreRow = !memory && all.length > 1 && cells.length === all.length &&
      cells.every((c) => c.dataset.mismatch === undefined);
    if (scoreRow) scored++;
    for (const cell of cells) {
      const r = ratio(Number(cell.dataset.value), top, higher, floor);
      cell.querySelector('.ratio').textContent = `${r.toFixed(2)}×`;
      cell.style.background = `hsl(${Math.round(10 + 110 * r)},65%,78%)`;
      cell.classList.toggle('best', r === 1);
      if (scoreRow) {
        const id = cell.dataset.variant;
        (ratios[id] ??= []).push(r);
        if (r === 1) wins[id] = (wins[id] ?? 0) + 1;
      }
    }
  }
  document.getElementById('score-basis').textContent =
    `Scores cover the ${scored} of ${speed} speed scenarios that every ` +
    'client completed using its expected protocol.';

  for (const track of document.querySelectorAll('#scores .track')) {
    const id = track.dataset.variant;
    const values = ratios[id] ?? [];
    // 0.01 mirrors `VariantScore.minimumRatio`.
    const score = values.length === 0
      ? 0
      : Math.exp(values.reduce(
          (sum, r) => sum + Math.log(Math.max(r, 0.01)), 0) / values.length);
    track.firstElementChild.style.width = `${(score * 100).toFixed(1)}%`;
    const count = wins[id] ?? 0;
    const failures = Number(track.dataset.failures);
    track.nextElementSibling.textContent = values.length === 0
      ? '–'
      : [
          `${score.toFixed(2)}×`,
          `${count} ${count === 1 ? 'win' : 'wins'}`,
          ...(failures > 0 ? [`${failures} failed`] : []),
        ].join(' · ');
  }
}

for (const checkbox of document.querySelectorAll('input[data-filter]')) {
  checkbox.addEventListener('change', () => {
    const id = checkbox.dataset.filter;
    if (checkbox.checked) {
      hidden.delete(id);
    } else {
      hidden.add(id);
    }
    const selector = `[data-variant="${CSS.escape(id)}"]`;
    for (const element of document.querySelectorAll(selector)) {
      element.classList.toggle('hidden', !checkbox.checked);
    }
    update();
  });
}
''';

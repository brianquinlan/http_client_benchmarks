/// Colors assigned to client variants, in order (Tableau 10).
const _palette = [
  '#4e79a7',
  '#f28e2b',
  '#59a14f',
  '#e15759',
  '#76b7b2',
  '#edc948',
  '#b07aa1',
  '#ff9da7',
  '#9c755f',
  '#bab0ac',
];

/// The concurrency of the scenarios used for the scaling chart.
const _scalingScenarios = {
  'get-sequential': 1,
  'get-concurrent-16': 16,
  'get-concurrent-128': 128,
};

const _htmlEscape = HtmlEscape();

String _e(Object? text) => _htmlEscape.convert('$text');

/// Formats [report] as a self-contained HTML page.
///
/// The page has no external dependencies: charts are rendered as inline SVG
/// and the raw results are embedded as JSON.
String htmlReport(BenchmarkReport report) => _HtmlReport(report).render();

class _HtmlReport {
  _HtmlReport(this.report)
    : colors = {
        for (final (i, variant) in report.availableVariants.indexed)
          variant.id: _palette[i % _palette.length],
      };

  final BenchmarkReport report;
  final Map<String, String> colors;
  final buffer = StringBuffer();

  late final summaries = {
    for (final scenario in report.scenarios)
      scenario.id: ScenarioSummary(report, scenario),
  };

  String render() {
    final environment = report.environment;
    final configuration = report.configuration;
    buffer
      ..writeln('<!DOCTYPE html>')
      ..writeln('<html lang="en">')
      ..writeln('<head>')
      ..writeln('<meta charset="utf-8">')
      ..writeln(
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
      )
      ..writeln('<title>package:http client benchmarks</title>')
      ..writeln('<style>$_css</style>')
      ..writeln('</head>')
      ..writeln('<body><main>')
      ..writeln('<header>')
      ..writeln('<h1>package:http client benchmarks</h1>')
      ..writeln('<div class="meta">${_e(environment.machine)}</div>')
      ..writeln('<div class="meta">${_e(environment.software)}</div>')
      ..writeln(
        '<div class="meta">${_e(report.startedAt.toLocal())} · '
        '${configuration.trials} trials (+${configuration.warmup} warmup) per '
        'scenario${configuration.quick ? ' · quick mode (reduced sizes)' : ''}'
        '${configuration.httpProfiling ? ' · HTTP profiling enabled' : ''}'
        '</div>',
      )
      ..writeln('</header>')
      ..writeln('<nav><a href="#summary">Summary</a>')
      ..writeln(
        _scalingScenarios.keys.every(summaries.containsKey)
            ? '<a href="#scaling">Scaling</a>'
            : '',
      );
    for (final category in report.categories) {
      buffer.writeln('<a href="#${_slug(category)}">${_e(category)}</a>');
    }
    buffer.writeln('</nav>');

    _writeClients();
    _writeSummary();
    _writeScaling();
    for (final category in report.categories) {
      buffer.writeln(
        '<section id="${_slug(category)}"><h2>${_e(category)}</h2>',
      );
      for (final scenario in report.scenarios) {
        if (scenario.category == category) {
          _writeScenario(summaries[scenario.id]!);
        }
      }
      buffer.writeln('</section>');
    }

    // Escaping "<" prevents the data from closing the <script> element (or
    // changing how its end is found, e.g. with "<!--").
    final json = jsonEncode(report.toJson()).replaceAll('<', r'\u003c');
    buffer
      ..writeln(
        '<footer class="meta">Generated by package:http_client_benchmarks. '
        'The raw results are embedded in this page as JSON '
        '(<code>#benchmark-data</code>).</footer>',
      )
      ..writeln('</main>')
      ..writeln(
        '<script type="application/json" id="benchmark-data">$json</script>',
      )
      ..writeln('<script>$_script</script>')
      ..writeln('</body></html>');
    return buffer.toString();
  }

  String _swatch(String variantId) =>
      '<span class="swatch" style="background:${colors[variantId]}"></span>';

  void _writeClients() {
    buffer
      ..writeln('<section class="card" id="clients">')
      ..writeln('<h3>Clients</h3>')
      ..writeln(
        '<p class="muted">Uncheck a client to hide it from the charts and '
        'tables.</p>',
      )
      ..writeln('<div class="legend">');
    for (final variant in report.availableVariants) {
      buffer.writeln(
        '<label><input type="checkbox" checked data-filter="${_e(variant.id)}">'
        '${_swatch(variant.id)}${_e(variant.name)} '
        '<span class="muted">${_e(variant.protocol.label)}</span></label>',
      );
    }
    buffer.writeln('</div>');
    final unavailable = [
      for (final variant in report.variants)
        if (!variant.available) variant,
    ];
    if (unavailable.isNotEmpty) {
      buffer.writeln('<p><strong>Unavailable:</strong></p><ul>');
      for (final variant in unavailable) {
        buffer.writeln(
          '<li>${_e(variant.name)} <span class="muted">'
          '${_e(variant.unavailableReason)}</span></li>',
        );
      }
      buffer.writeln('</ul>');
    }
    buffer.writeln('</section>');
  }

  void _writeSummary() {
    final scores = scoreVariants(report);
    buffer
      ..writeln('<section id="summary"><h2>Summary</h2>')
      ..writeln(
        '<p>Geometric mean of each client\'s performance relative to the '
        'best client in each scenario (1.00× means best in every scenario). '
        'Scenarios that measure memory use are excluded. Hiding a client '
        'recomputes the scores without it.</p>',
      )
      ..writeln(
        '<p class="muted" id="score-basis">${_e(scoreBasis(report, scores))}'
        '</p>',
      )
      ..writeln('<div class="bars" id="scores">');
    for (final score in scores) {
      final value = score.score;
      final label = value == null
          ? '–'
          : [
              formatRatio(value),
              '${score.wins} ${score.wins == 1 ? 'win' : 'wins'}',
              if (score.failures > 0) '${score.failures} failed',
            ].join(' · ');
      buffer.writeln(
        _barRow(
          score.variant,
          value ?? 0,
          label,
          trackAttributes: 'data-failures="${score.failures}"',
        ),
      );
    }
    buffer
      ..writeln('</div>')
      ..writeln('<h3>Scoreboard</h3>')
      ..writeln(
        '<p class="muted">Performance relative to the best client in each '
        'scenario. ✗ marks failures and ! marks runs where the server '
        'received requests using an unexpected protocol. Hover over a cell '
        'to see the measured value.</p>',
      )
      ..writeln('<div class="scroll"><table class="heatmap"><thead><tr>')
      ..writeln('<th class="left">Scenario</th>');
    for (final variant in report.availableVariants) {
      buffer.writeln(
        '<th data-variant="${_e(variant.id)}">${_swatch(variant.id)}'
        '${_e(variant.client)}<br>${_e(variant.protocol.id)}</th>',
      );
    }
    buffer.writeln('</tr></thead><tbody>');
    for (final scenario in report.scenarios) {
      final summary = summaries[scenario.id]!;
      final metric = scenario.metric;
      buffer.writeln(
        '<tr ${_metricAttributes(metric)}><td class="left">'
        '<a href="#${_e(scenario.id)}">${_e(scenario.id)}</a></td>',
      );
      for (final variant in report.availableVariants) {
        final ranked = summary.ranked
            .where((r) => r.variant.id == variant.id)
            .firstOrNull;
        final attributes = 'data-variant="${_e(variant.id)}"';
        if (ranked == null || ranked.ratio == null) {
          final failed = ranked?.result.status == RunStatus.failed;
          buffer.writeln(
            '<td class="empty${failed ? ' fail' : ''}" $attributes '
            'title="${_e(ranked?.result.message ?? '')}">'
            '${failed ? '✗' : '–'}</td>',
          );
          continue;
        }
        final ratio = ranked.ratio!;
        final hue = (10 + 110 * ratio).round();
        final median = ranked.result.metric!.p50;
        final warning = ranked.protocolMismatch
            ? '<span class="warn"> !</span>'
            : '';
        buffer.writeln(
          '<td $attributes data-value="$median" '
          '${ranked.protocolMismatch ? 'data-mismatch="true" ' : ''}'
          'class="${ratio == 1 ? 'best' : ''}" '
          'style="background:hsl($hue,65%,78%)" '
          'title="${_e(formatMetric(metric, median))}">'
          '<span class="ratio">${formatRatio(ratio)}</span>$warning</td>',
        );
      }
      buffer.writeln('</tr>');
    }
    buffer.writeln('</tbody></table></div></section>');
  }

  /// Attributes that let the page's script compare values of [metric].
  String _metricAttributes(Metric metric) =>
      'data-higher="${metric.higherIsBetter}" '
      'data-floor="${metric.noiseFloor}" '
      'data-memory="${metric.measuresMemory}"';

  void _writeScaling() {
    if (!_scalingScenarios.keys.every(summaries.containsKey)) return;
    final series = <_Series>[];
    for (final variant in report.availableVariants) {
      final points = <(double, double)>[];
      for (final MapEntry(key: id, value: concurrency)
          in _scalingScenarios.entries) {
        final result = report.result(id, variant.id);
        if (result == null || !result.isOk) break;
        points.add((concurrency.toDouble(), result.requestsPerSecond!));
      }
      if (points.length == _scalingScenarios.length) {
        series.add(
          _Series(variant.id, variant.name, colors[variant.id]!, points),
        );
      }
    }
    if (series.isEmpty) return;
    buffer
      ..writeln('<section id="scaling"><h2>Concurrency scaling</h2>')
      ..writeln(
        '<p>Requests per second for 1 KiB GETs as the number of concurrent '
        'requests grows (<a href="#get-sequential">get-sequential</a>, '
        '<a href="#get-concurrent-16">get-concurrent-16</a> and '
        '<a href="#get-concurrent-128">get-concurrent-128</a>).</p>',
      )
      ..writeln('<div class="card">')
      ..writeln(
        _lineChart(
          series: series,
          xValues: [for (final c in _scalingScenarios.values) c.toDouble()],
          xLabel: formatNumber,
          yLabel: formatNumber,
          xTitle: 'Concurrent requests',
          yTitle: 'Requests/s',
          tooltip: (s, x, y) =>
              '${s.name}: ${formatNumber(y)} req/s at concurrency '
              '${x.round()}',
        ),
      )
      ..writeln('</div></section>');
  }

  String _barRow(
    VariantInfo variant,
    double fraction,
    String label, {
    String trackAttributes = '',
  }) {
    final attributes = 'data-variant="${_e(variant.id)}"';
    final width = (fraction.clamp(0, 1) * 100).toStringAsFixed(1);
    return '<div class="label" $attributes>${_swatch(variant.id)}'
        '${_e(variant.name)}</div>'
        '<div class="track" $attributes $trackAttributes><div class="bar" '
        'style="width:$width%;background:${colors[variant.id]}"></div></div>'
        '<div class="value" $attributes>$label</div>';
  }

  void _writeScenario(ScenarioSummary summary) {
    final scenario = summary.scenario;
    final metric = summary.metric;
    final sample = sampleLabels[summary.sampleName]!;
    buffer
      ..writeln('<article class="card" id="${_e(scenario.id)}">')
      ..writeln(
        '<h3>${_e(scenario.title)} <code class="muted">'
        '${_e(scenario.id)}</code></h3>',
      )
      ..writeln('<p>${_inlineCode(scenario.description)}</p>')
      ..writeln(
        '<p class="muted">${_e(metric.label)} '
        '(${metric.higherIsBetter ? 'higher' : 'lower'} is better); bars '
        'show performance relative to the best client.</p>',
      )
      ..writeln('<div class="bars" ${_metricAttributes(metric)}>');
    final notes = <String>[];
    for (final ranked in summary.ranked) {
      final result = ranked.result;
      final variant = ranked.variant;
      if (ranked.protocolMismatch) {
        notes.add(
          '<span class="warn">!</span> ${_e(variant.name)}: the server '
          'received ${_e(ranked.protocolDescription)}.',
        );
      }
      if (!result.isOk) {
        final failed = result.status == RunStatus.failed;
        buffer.writeln(
          _barRow(
            variant,
            0,
            '<span class="${failed ? 'fail' : 'muted'}">'
            '${failed ? '✗ failed' : 'skipped'}</span>',
          ),
        );
        notes.add('${_e(variant.name)}: ${_e(result.message)}');
        continue;
      }
      final median = result.metric!.p50;
      final value = _e(formatMetric(metric, median));
      final spread = formatPercent(result.metric!.relativeSpread);
      final warning = ranked.protocolMismatch
          ? ' <span class="warn">!</span>'
          : '';
      buffer.writeln(
        _barRow(
          variant,
          ranked.ratio!,
          '$value <span class="muted">±$spread</span>$warning',
          trackAttributes: 'data-value="$median"',
        ),
      );
      for (final note in result.notes.values) {
        notes.add('${_e(variant.name)}: ${_e(note)}');
      }
    }
    buffer.writeln('</div>');
    if (notes.isNotEmpty) {
      buffer.writeln('<ul class="notes">');
      for (final note in notes) {
        buffer.writeln('<li>$note</li>');
      }
      buffer.writeln('</ul>');
    }

    buffer
      ..writeln('<details><summary>Details</summary>')
      ..writeln('<div class="scroll"><table><thead><tr>')
      ..writeln(
        [
          '<th class="left">Client</th>',
          '<th>Proto</th>',
          '<th>${_e(metric.label)}</th>',
          '<th>$sample p50</th>',
          '<th>$sample p90</th>',
          '<th>$sample p99</th>',
          '<th>TTFB p50</th>',
          '<th>Requests/s</th>',
          '<th>MB/s</th>',
          '<th>Conns</th>',
          '<th>Peak RSS</th>',
        ].join(),
      )
      ..writeln('</tr></thead><tbody>');
    for (final ranked in summary.ranked) {
      final result = ranked.result;
      if (!result.isOk) continue;
      final samples = result.samples[summary.sampleName];
      final ttfb = result.samples['ttfb'];
      String micros(double? value) =>
          value == null ? '–' : formatMicroseconds(value);
      buffer.writeln(
        '<tr data-variant="${_e(ranked.variant.id)}">'
        '<td class="left">${_swatch(ranked.variant.id)}'
        '${_e(ranked.variant.client)}</td>'
        '<td>${_e(ranked.variant.protocol.id)}</td>'
        '<td>${_e(formatMetric(metric, result.metric!.p50))}</td>'
        '<td>${micros(samples?.p50)}</td>'
        '<td>${micros(samples?.p90)}</td>'
        '<td>${micros(samples?.p99)}</td>'
        '<td>${micros(ttfb?.p50)}</td>'
        '<td>${formatNumber(result.requestsPerSecond!)}</td>'
        '<td>${formatNumber(result.megabytesPerSecond!, decimals: 1)}</td>'
        '<td>${result.connectionsUsed}</td>'
        '<td>${formatSizeDelta(result.peakRssDelta!)}</td></tr>',
      );
    }
    buffer.writeln('</tbody></table></div>');

    final percentileSeries = [
      for (final ranked in summary.ranked)
        if (ranked.result.samples[summary.sampleName] case final distribution?
            when ranked.result.isOk)
          _Series(
            ranked.variant.id,
            ranked.variant.name,
            colors[ranked.variant.id]!,
            [
              for (final (i, key) in _percentileKeys.indexed)
                (
                  i.toDouble(),
                  key == 'max'
                      ? distribution.max
                      : distribution.percentiles[double.parse(key)]!,
                ),
            ],
          ),
    ];
    if (percentileSeries.isNotEmpty) {
      buffer
        ..writeln('<p class="muted">$sample percentiles across all trials:</p>')
        ..writeln(
          _lineChart(
            series: percentileSeries,
            xValues: [
              for (var i = 0; i < _percentileKeys.length; i++) i.toDouble(),
            ],
            xLabel: _percentileLabel,
            yLabel: formatMicroseconds,
            xTitle: 'Percentile',
            yTitle: sample,
            logY: true,
            tooltip: (s, x, y) =>
                '${s.name}: ${_percentileLabel(x)} = ${formatMicroseconds(y)}',
          ),
        );
    }
    buffer.writeln('</details></article>');
  }
}

/// The points plotted on percentile charts.
const _percentileKeys = ['50', '75', '90', '95', '99', '99.9', 'max'];

String _percentileLabel(double x) {
  final key = _percentileKeys[x.round()];
  return key == 'max' ? 'max' : 'p$key';
}

String _slug(String text) =>
    text.toLowerCase().replaceAll(RegExp('[^a-z0-9]+'), '-');

/// Escapes [text] and converts `code` spans into `<code>` elements.
String _inlineCode(String text) => _e(
  text,
).replaceAllMapped(RegExp('`([^`]+)`'), (m) => '<code>${m[1]}</code>');

class _Series {
  _Series(this.variantId, this.name, this.color, this.points);

  final String variantId;
  final String name;
  final String color;
  final List<(double, double)> points;
}

double _niceStep(double range, int targetTicks) {
  final rough = range / targetTicks;
  final magnitude = math
      .pow(10, (math.log(rough) / math.ln10).floor())
      .toDouble();
  final residual = rough / magnitude;
  final nice = residual > 5
      ? 10
      : residual > 2
      ? 5
      : residual > 1
      ? 2
      : 1;
  return nice * magnitude;
}

/// Renders a line chart as SVG.
///
/// Points are placed at evenly spaced x positions, in the order of
/// [xValues].
String _lineChart({
  required List<_Series> series,
  required List<double> xValues,
  required String Function(double) xLabel,
  required String Function(double) yLabel,
  required String xTitle,
  required String yTitle,
  required String Function(_Series series, double x, double y) tooltip,
  bool logY = false,
}) {
  const width = 760.0;
  const height = 300.0;
  const left = 80.0;
  const right = 24.0;
  const top = 16.0;
  const bottom = 48.0;
  const plotWidth = width - left - right;
  const plotHeight = height - top - bottom;

  final ys = [
    for (final s in series)
      for (final (_, y) in s.points) y,
  ];
  var minY = ys.reduce(math.min);
  var maxY = ys.reduce(math.max);
  // Use a logarithmic scale only when the values span a wide range.
  final useLog = logY && minY > 0 && maxY / minY > 8;
  final ticks = <double>[];
  if (useLog) {
    // Candidate ticks follow the 1-2-5 sequence; keep those that tightly
    // bracket the data.
    final candidates = <double>[];
    var decade = math.pow(10, (math.log(minY) / math.ln10).floor()).toDouble();
    while (true) {
      for (final multiple in const [1, 2, 5]) {
        candidates.add(decade * multiple);
      }
      if (decade * 5 >= maxY) break;
      decade *= 10;
    }
    final lowest = minY;
    final highest = maxY;
    minY = candidates.lastWhere((t) => t <= lowest);
    maxY = candidates.firstWhere((t) => t >= highest);
    ticks.addAll(candidates.where((t) => t >= minY && t <= maxY));
  } else {
    minY = 0;
    final step = _niceStep(maxY == 0 ? 1 : maxY, 5);
    maxY = (maxY / step).ceil() * step;
    if (maxY == 0) maxY = step;
    for (var tick = 0.0; tick <= maxY * 1.0001; tick += step) {
      ticks.add(tick);
    }
  }

  double xPosition(double x) {
    final index = xValues.indexOf(x);
    return xValues.length == 1
        ? left + plotWidth / 2
        : left + plotWidth * index / (xValues.length - 1);
  }

  double yPosition(double y) {
    final fraction = useLog
        ? (math.log(y) - math.log(minY)) / (math.log(maxY) - math.log(minY))
        : (y - minY) / (maxY - minY);
    return top + plotHeight * (1 - fraction);
  }

  String n(double value) => value.toStringAsFixed(1);

  final svg = StringBuffer(
    '<svg class="chart" viewBox="0 0 ${width.toInt()} ${height.toInt()}" '
    'role="img" aria-label="${_e(yTitle)} by ${_e(xTitle)}">',
  );
  for (final tick in ticks) {
    final y = yPosition(tick);
    svg
      ..write(
        '<line class="grid" x1="$left" x2="${width - right}" '
        'y1="${n(y)}" y2="${n(y)}"/>',
      )
      ..write(
        '<text x="${left - 8}" y="${n(y + 4)}" text-anchor="end">'
        '${_e(yLabel(tick))}</text>',
      );
  }
  for (final x in xValues) {
    svg.write(
      '<text x="${n(xPosition(x))}" y="${height - bottom + 18}" '
      'text-anchor="middle">${_e(xLabel(x))}</text>',
    );
  }
  svg
    ..write(
      '<text x="${left + plotWidth / 2}" y="${height - 6}" '
      'text-anchor="middle">${_e(xTitle)}</text>',
    )
    ..write(
      '<text transform="translate(14 ${top + plotHeight / 2}) rotate(-90)" '
      'text-anchor="middle">${_e(yTitle)}</text>',
    );
  for (final s in series) {
    final points = [
      for (final (x, y) in s.points) '${n(xPosition(x))},${n(yPosition(y))}',
    ].join(' ');
    svg.write(
      '<g data-variant="${_e(s.variantId)}">'
      '<polyline points="$points" fill="none" stroke="${s.color}" '
      'stroke-width="2"/>',
    );
    for (final (x, y) in s.points) {
      svg.write(
        '<circle cx="${n(xPosition(x))}" cy="${n(yPosition(y))}" r="3.5" '
        'fill="${s.color}"><title>${_e(tooltip(s, x, y))}</title></circle>',
      );
    }
    svg.write('</g>');
  }
  svg.write('</svg>');
  return svg.toString();
}

